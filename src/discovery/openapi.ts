/**
 * Builds an OpenAPI 3.0 document from the discovered routes.
 * Request bodies and query params come from the route's zod schema when the
 * validation module can be loaded (needs the backend's node_modules); every
 * other route gets a permissive schema so fuzzers can still exercise it.
 */
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { zodToJsonSchema } from "zod-to-json-schema";
import type { RouteInfo } from "../core/types.js";

const toOpenApiPath = (p: string) => p.replace(/:([A-Za-z0-9_]+)/g, "{$1}");
const opId = (r: RouteInfo) => (r.method.toLowerCase() + r.path.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))).slice(0, 120);

const ENVELOPE = {
  type: "object",
  properties: { success: { type: "boolean" }, message: { type: "string" }, data: {}, pagination: { type: "object" } },
};

async function loadZod(r: RouteInfo, cache: Map<string, any>, failures: Set<string>) {
  if (!r.validation) return undefined;
  const { file, exportName, key } = r.validation;
  if (failures.has(file)) return undefined;
  try {
    if (!cache.has(file)) cache.set(file, await import(pathToFileURL(file).href));
    const mod = cache.get(file);
    const holder = mod[exportName] ?? mod.default?.[exportName] ?? mod["module.exports"]?.[exportName];
    const schema = holder?.[key];
    if (!schema?._def) return undefined;
    // validateRequest parses { body, params, query, cookies }
    const shape = typeof schema.shape === "object" ? schema.shape : schema._def.shape?.();
    return shape as Record<string, any> | undefined;
  } catch {
    failures.add(file);
    return undefined;
  }
}

const jsonSchema = (z: any) => {
  const s: any = zodToJsonSchema(z, { target: "openApi3", $refStrategy: "none" });
  delete s.$schema;
  return s;
};

export async function buildOpenApi(routes: RouteInfo[], opts: { title: string; serverUrl?: string; outFile: string }) {
  const cache = new Map<string, any>();
  const failures = new Set<string>();
  let zodResolved = 0;
  const paths: Record<string, any> = {};

  for (const r of routes) {
    const p = toOpenApiPath(r.path);
    paths[p] ??= {};
    const params = [...r.path.matchAll(/:([A-Za-z0-9_]+)/g)].map((m) => ({ name: m[1], in: "path", required: true, schema: { type: "string" } }));
    const op: any = {
      operationId: opId(r),
      tags: [r.module],
      summary: `${r.method} ${r.apiPath}`,
      parameters: params,
      responses: { default: { description: "Standard response envelope", content: { "application/json": { schema: ENVELOPE } } } },
      "x-source": `${r.source.file}:${r.source.line}`,
      "x-roles": r.roles,
    };
    if (r.authRequired) op.security = [{ bearerAuth: [] }];

    const shape = await loadZod(r, cache, failures);
    if (shape) zodResolved++;
    if (shape?.query) {
      const qs = jsonSchema(shape.query);
      for (const [name, s] of Object.entries<any>(qs.properties ?? {})) {
        op.parameters.push({ name, in: "query", required: (qs.required ?? []).includes(name), schema: s });
      }
    }
    if (["POST", "PUT", "PATCH"].includes(r.method)) {
      if (r.multipart) {
        op.requestBody = { content: { "multipart/form-data": { schema: { type: "object", additionalProperties: true } } } };
      } else {
        const body = shape?.body ? jsonSchema(shape.body) : { type: "object", additionalProperties: true };
        op.requestBody = { required: !!shape?.body, content: { "application/json": { schema: body } } };
      }
    }
    paths[p][r.method.toLowerCase()] = op;
  }

  const doc = {
    openapi: "3.0.3",
    info: { title: opts.title, version: "generated", description: "Generated by the QA agent from Express route source. Do not edit by hand." },
    servers: opts.serverUrl ? [{ url: opts.serverUrl }] : [],
    components: { securitySchemes: { bearerAuth: { type: "http", scheme: "bearer", bearerFormat: "JWT" } } },
    paths,
  };
  fs.mkdirSync(path.dirname(opts.outFile), { recursive: true });
  fs.writeFileSync(opts.outFile, JSON.stringify(doc, null, 2));
  return { file: opts.outFile, operations: routes.length, zodResolved, zodFailedFiles: [...failures] };
}
