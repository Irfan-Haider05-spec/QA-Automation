/**
 * CI wording and file generators: how a run was triggered, links to GitHub, and
 * the workflow + config files the CI setup tab hands to the user.
 */
import type { GitInfo, Run } from "../api/types.js"; // .js: also compiled by the engine's test (NodeNext)

/** Short, human description of why a run happened */
export function triggerText(r: Pick<Run, "trigger" | "source" | "git" | "deployment">): string {
  switch (r.trigger) {
    case "pr": return r.git?.pr ? `PR #${r.git.pr}` : "Pull request";
    case "deploy": return `Deploy ${r.deployment?.version ?? r.deployment?.sha?.slice(0, 7) ?? r.git?.sha?.slice(0, 7) ?? ""}`.trim();
    case "schedule": return "Schedule";
    case "push": return r.git?.ref ? `Push to ${r.git.ref}` : "Push";
    case "manual": return r.source === "hosted" ? "Run now" : "Manual";
    default: return r.source === "cli" ? "Local run" : r.source === "hosted" ? "Hosted runner" : "CI";
  }
}

/** Links to the commit, PR and CI job, when the run came from GitHub */
export function gitLinks(git: GitInfo | null | undefined) {
  if (!git?.repo) return { ciUrl: git?.ciUrl };
  // GitHub Enterprise: take the server from the job link
  let server = "https://github.com";
  try { if (git.ciUrl) server = new URL(git.ciUrl).origin; } catch { /* keep github.com */ }
  const repoUrl = `${server}/${git.repo}`;
  return {
    repoUrl,
    commitUrl: git.sha ? `${repoUrl}/commit/${git.sha}` : undefined,
    prUrl: git.pr ? `${repoUrl}/pull/${git.pr}` : undefined,
    ciUrl: git.ciUrl,
  };
}

export interface WorkflowOptions {
  platformUrl: string;
  environmentId: string | null;
  actionRef: string;
  stagingBranch: string;
  /** Use test accounts stored on the platform (needs a key that can read them) */
  platformAccounts: boolean;
}

const q = (s: string) => (/^[\w./:@-]+$/.test(s) ? s : JSON.stringify(s));

export function workflowYaml(o: WorkflowOptions): string {
  const staging = o.environmentId
    ? `
  staging:
    if: github.event_name != 'pull_request'
    runs-on: ubuntu-latest
    timeout-minutes: 45
    # Test accounts usually allow one session at a time: never run two staging jobs at once
    concurrency:
      group: qa-staging
      cancel-in-progress: false
    steps:
      - uses: actions/checkout@v4

      - uses: ${o.actionRef}
        with:
          suite: \${{ github.event_name == 'schedule' && 'nightly' || 'staging' }}
          base-url: \${{ vars.QA_STAGING_URL }}
          wait-for-deploy: \${{ github.event_name == 'push' }}
          after-deploy: \${{ github.event_name == 'push' }}
          platform-url: \${{ env.QA_PLATFORM_URL }}
          platform-api-key: \${{ secrets.QA_PLATFORM_API_KEY }}
          platform-environment: \${{ env.QA_PLATFORM_ENV }}
          platform-accounts: "${o.platformAccounts}"
`
    : "";
  return `# QA Agent: generated by the QA platform's CI setup tab.
# Save as .github/workflows/qa.yml
#   pull_request  tests the routes the PR touches, comments on the PR, sets a "QA gate" status${o.environmentId ? `
#   push ${o.stagingBranch.padEnd(9)}waits for the new deploy, reports it, runs the staging suite
#   nightly       full nightly suite against staging` : ""}
# Needs: secret QA_PLATFORM_API_KEY${o.environmentId ? ", variable QA_STAGING_URL" : ""}
name: QA

on:
  pull_request:${o.environmentId ? `
  push:
    branches: [${q(o.stagingBranch)}]
  schedule:
    - cron: "41 21 * * *"` : ""}
  workflow_dispatch:

permissions:
  contents: read
  pull-requests: write
  statuses: write

env:
  QA_PLATFORM_URL: ${q(o.platformUrl)}${o.environmentId ? `
  QA_PLATFORM_ENV: ${o.environmentId}` : ""}

jobs:
  pr:
    if: github.event_name == 'pull_request'
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      # Static checks run on the code alone. To also test this PR's backend live,
      # start it here and add base-url (e.g. http://localhost:3000) below.

      - uses: ${o.actionRef}
        with:
          suite: pr
          platform-url: \${{ env.QA_PLATFORM_URL }}
          platform-api-key: \${{ secrets.QA_PLATFORM_API_KEY }}
${staging}`;
}

const STACK_LAYOUT: Record<string, { routesIndex: string; appFile: string; modulesDir: string; apiPrefix: string }> = {
  "node-express": { routesIndex: "src/app/routes/index.ts", appFile: "src/app.ts", modulesDir: "src/app/modules", apiPrefix: "/api/v1" },
  nestjs: { routesIndex: "src/app.module.ts", appFile: "src/main.ts", modulesDir: "src", apiPrefix: "/api" },
};

export function configTs(o: { projectName: string; stack: string; accounts: Array<{ name: string; role: string }> }): string {
  const layout = STACK_LAYOUT[o.stack] ?? STACK_LAYOUT["node-express"];
  const env = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();
  const accounts = o.accounts.length
    ? o.accounts.map((a) => `    ${a.name}: { identifier: process.env.QA_${env(a.name)}_ID, password: process.env.QA_${env(a.name)}_PASS, role: ${JSON.stringify(a.role)}, device: "" },`).join("\n")
    : `    // merchantA: { identifier: process.env.QA_MERCHANT_A_ID, password: process.env.QA_MERCHANT_A_PASS, role: "MERCHANT", device: "merchant" },`;
  const pair = o.accounts.length >= 2 ? `owner: ${JSON.stringify(o.accounts[0].name)}, attacker: ${JSON.stringify(o.accounts[1].name)}` : `owner: "merchantA", attacker: "merchantB"`;
  return `// QA Agent config: generated by the QA platform's CI setup tab. Save as qa.config.ts at the repo root.
// Accounts: with platform-accounts enabled in the workflow, logins come from the platform's
// vault and the env vars below can stay unset. Values set here or in env vars win.
export default {
  project: ${JSON.stringify(o.projectName)},
  backend: {
    dir: ".",
    routesIndex: ${JSON.stringify(layout.routesIndex)}, // file that mounts your routers
    appFile: ${JSON.stringify(layout.appFile)},
    apiPrefix: ${JSON.stringify(layout.apiPrefix)},
    healthPath: "/health",
    envExample: ".env.example",
    modulesDir: ${JSON.stringify(layout.modulesDir)},
  },
  target: { requestsPerMinute: 90, timeoutMs: 15000, slowMs: 2000 },
  login: { path: "${layout.apiPrefix}/auth/login", tokenPath: "data.accessToken" },
  accounts: {
${accounts}
  },
  // Routes meant to work without a token
  publicRoutes: ["GET /health", "POST /auth/login"],
  // Route prefixes that must always check roles
  privilegedPrefixes: ["/admin"],
  tenantIsolation: { ${pair}, sharedResources: [], pairs: [], maxIdsPerRoute: 3 },
  // A change in these files tests every route
  globalPaths: [${JSON.stringify(layout.appFile)}, "src/**/middlewares/**", "src/config/**"],
  suites: {
    pr: ["route-auth", "env-drift", "secrets", "health-cors", "api-auth", "api-smoke", "tenant-isolation"],
    staging: ["health-cors", "api-auth", "api-smoke", "tenant-isolation"],
    nightly: ["route-auth", "env-drift", "secrets", "health-cors", "api-auth", "api-smoke", "tenant-isolation", "load-smoke", "zap-baseline"],
    local: ["route-auth", "env-drift", "secrets"],
  },
  gate: { failOn: "high" },
  // Load smoke at night: GET only, never more than 2 requests/s unless you raise it
  load: { maxRps: 2, durationSec: 30 },
  knownIssuesFile: "qa-known-issues.json",
};
`;
}
